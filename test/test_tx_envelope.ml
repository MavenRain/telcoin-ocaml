let minimal_legacy ~kind ~data =
  Tx_payload.legacy ~nonce:(Tx_vectors.nonce_of 0) ~gas_price:U256.zero ~gas_limit:0 ~kind
    ~value:U256.zero ~data ~chain_id:None

let minimal_2930 ~access_list =
  Tx_payload.eip2930 ~chain_id:U256.zero ~nonce:(Tx_vectors.nonce_of 0) ~gas_price:U256.zero
    ~gas_limit:0 ~kind:Transaction.Create ~value:U256.zero ~data:"" ~access_list

let test_structural_constants () =
  let sp p = to_hex (Tx_envelope.signing_payload p) in
  Alcotest.(check string)
    "Create's `to` is the single byte 0x80" "c6808080808080"
    (sp (minimal_legacy ~kind:Transaction.Create ~data:""));
  Alcotest.(check string)
    "the zero address is 0x94 + twenty zero bytes, never 0x80"
    ("da808080" ^ "94" ^ zero20 ^ "8080")
    (sp (minimal_legacy ~kind:(Transaction.Call Address.zero) ~data:""));
  Alcotest.(check string)
    "one-byte calldata 0x2a is the bare byte" "c680808080802a"
    (sp (minimal_legacy ~kind:Transaction.Create ~data:"\x2a"));
  Alcotest.(check string)
    "one-byte calldata 0x80 is 0x81 0x80" "c780808080808180"
    (sp (minimal_legacy ~kind:Transaction.Create ~data:"\x80"));
  Alcotest.(check string)
    "an empty access list is the single byte 0xc0" "01c880808080808080c0"
    (sp (minimal_2930 ~access_list:[]));
  Alcotest.(check string)
    "an item with zero keys is d6 94 <20B> c0"
    ("01df80808080808080" ^ "d7d694" ^ zero20 ^ "c0")
    (sp (minimal_2930 ~access_list:[ (Address.zero, []) ]));
  Alcotest.(check string)
    "an item with one key sits exactly on the 55/56 payload boundary"
    ("01f84180808080808080" ^ "f838f794" ^ zero20 ^ "e1a0" ^ String.make 62 '0' ^ "01")
    (sp (minimal_2930 ~access_list:[ (Address.zero, [ U256.one ]) ]))

(* The two EIP-155 signing zeros are the NUMBER zero (0x80 0x80), and the tail is
   omitted entirely without a chain id. *)
let test_eip155_signing_tail () =
  Alcotest.(check string)
    "no chain id: six items, no tail" "c6808080808080"
    (to_hex (Tx_envelope.signing_payload (minimal_legacy ~kind:Transaction.Create ~data:"")));
  Alcotest.(check string)
    "chain id 0: nine items, tail 0x80 0x80 0x80" "c9808080808080808080"
    (to_hex
       (Tx_envelope.signing_payload
          (Tx_payload.legacy ~nonce:(Tx_vectors.nonce_of 0) ~gas_price:U256.zero ~gas_limit:0
             ~kind:Transaction.Create ~value:U256.zero ~data:"" ~chain_id:(Some U256.zero))))

