let test_must_accept () =
  check_accept "r = 0" (legacy_of (replace 7 (b "80") legacy_fields));
  check_accept "s = 0" (legacy_of (replace 8 (b "80") legacy_fields));
  check_accept "s >= n (all-ones)"
    (legacy_of (replace 8 (b ("a0" ^ String.make 64 'f')) legacy_fields));
  check_accept "s > secp256k1n/2 (high s decodes; recovery is where it fails)"
    (legacy_of (replace 8 (b "a0fffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364140")
                  legacy_fields));
  check_accept "legacy with no chain id (v = 27)" (legacy_of legacy_fields);
  check_accept "legacy chain_id = 0 (v = 35)" (legacy_of (replace 6 (b "23") legacy_fields));
  check_accept "legacy chain id exactly u64::MAX"
    (legacy_of (replace 6 (b "89020000000000000022") legacy_fields));
  check_accept "typed chain_id = 0" (t1_of (replace 0 (b "80") t1_fields));
  check_accept "access-list item with zero storage keys"
    (t1_of (replace 7 (al_of [ al_item ("94" ^ to_a) [] ]) t1_fields));
  check_accept "access list with duplicate addresses and repeated keys"
    (t1_of
       (replace 7
          (al_of
             [ al_item ("94" ^ to_a) [ key32; key32 ]; al_item ("94" ^ to_a) [ key32 ] ])
          t1_fields))

(* chain_id = Some 0 is NOT the same as None: the two differ in v and therefore
   in every byte downstream. *)
let test_chain_id_zero_distinct_from_none () =
  let decoded_chain_id bytes =
    Result.fold ~error:(fun _ -> None)
      ~ok:(fun e -> Tx_payload.chain_id (Tx_envelope.payload e))
      (Tx_envelope.decode_2718 bytes)
  in
  Alcotest.(check bool)
    "v = 27 gives no chain id" true
    (Option.is_none (decoded_chain_id (legacy_of legacy_fields)));
  Alcotest.(check bool)
    "v = 35 gives chain id Some 0" true
    (Option.equal U256.equal (Some U256.zero)
       (decoded_chain_id (legacy_of (replace 6 (b "23") legacy_fields))))

