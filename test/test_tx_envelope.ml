let to_a = Tx_vectors.to_a
let zero20 = String.make 40 '0'
let r32 = "a0" ^ String.make 64 '1'
let s32 = "a0" ^ String.make 64 '1'

(* A valid legacy envelope's nine chunks: nonce, gas_price, gas_limit, to, value,
   input, v, r, s. v = 0x1b = 27, i.e. parity false and no chain id. *)
let legacy_fields =
  [ b "80"; b "80"; b "825208"; b ("94" ^ to_a); b "80"; b "80"; b "1b"; b r32; b s32 ]

let legacy_of fields = Rlp.encode_list fields

(* A valid EIP-2930 envelope's eleven chunks. *)
let key32 = "a0" ^ String.make 64 '2'

let t1_fields =
  [
    b "01"; b "80"; b "80"; b "825208"; b ("94" ^ to_a); b "80"; b "80"; b "c0"; b "80"; b r32;
    b s32;
  ]

let t1_of fields = "\x01" ^ Rlp.encode_list fields

(* A valid EIP-1559 envelope's twelve chunks, in wire order: chain_id, nonce,
   max_priority_fee_per_gas, max_fee_per_gas, gas_limit, to, value, input,
   access_list, y_parity, r, s — the tip cap before the fee cap. *)
let t2_fields =
  [
    b "01"; b "80"; b "80"; b "80"; b "825208"; b ("94" ^ to_a); b "80"; b "80"; b "c0"; b "80";
    b r32; b s32;
  ]

let t2_of fields = "\x02" ^ Rlp.encode_list fields
let replace i v xs = List.mapi (fun j x -> if Int.equal j i then v else x) xs
let drop_last xs = List.filteri (fun j _ -> j < List.length xs - 1) xs
let al_of items = Rlp.encode_list items
let al_item addr keys = Rlp.encode_list [ b addr; Rlp.encode_list (List.map b keys) ]

let check_reject name bytes expected =
  Alcotest.(check string)
    name
    (Tx_envelope.error_to_string expected)
    (Result.fold ~ok:(fun _ -> "Ok (accepted)") ~error:Tx_envelope.error_to_string
       (Tx_envelope.decode_2718 bytes))

let check_accept name bytes =
  Alcotest.(check string)
    name "Ok (accepted)"
    (Result.fold ~ok:(fun _ -> "Ok (accepted)") ~error:Tx_envelope.error_to_string
       (Tx_envelope.decode_2718 bytes))

(* The signature scalars are RLP SCALARS, not fixed 32-byte strings: an envelope
   whose r or s is short must round-trip to its own shorter bytes, and its hash
   is a different hash. Every oracle fixture happens to have a full-width r and
   s, so nothing above would notice an encoder that wrote them fixed-width — this
   is where that choice is pinned. *)
let test_round_trip_short_scalars () =
  let round bytes =
    Result.fold ~error:Tx_envelope.error_to_string
      ~ok:(fun e -> to_hex (Tx_envelope.encode_2718 e))
      (Tx_envelope.decode_2718 bytes)
  in
  List.iter
    (fun (label, bytes) ->
      Alcotest.(check string) ("round trip: " ^ label) (to_hex bytes) (round bytes))
    [
      ("base legacy", legacy_of legacy_fields);
      ("base typed", t1_of t1_fields);
      ("r = 0", legacy_of (replace 7 (b "80") legacy_fields));
      ("one-byte r", legacy_of (replace 7 (b "01") legacy_fields));
      ("31-byte s", legacy_of (replace 8 (b ("9f" ^ String.make 62 '3')) legacy_fields));
      ("s = 0", legacy_of (replace 8 (b "80") legacy_fields));
      ("one-byte typed r", t1_of (replace 9 (b "01") t1_fields));
    ]

