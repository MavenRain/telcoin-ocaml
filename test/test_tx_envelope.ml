(* 4. The rejection table                                              *)
(* ------------------------------------------------------------------ *)

let test_base_vectors_decode () =
  check_accept "base legacy chunk vector decodes" (legacy_of legacy_fields);
  check_accept "base EIP-2930 chunk vector decodes" (t1_of t1_fields)

let test_reject_scalars () =
  check_reject "nonce 0x00" (legacy_of (replace 0 (b "00") legacy_fields))
    Tx_envelope.Leading_zero_scalar;
  check_reject "nonce 0x82 0x00 0x01" (legacy_of (replace 0 (b "820001") legacy_fields))
    Tx_envelope.Leading_zero_scalar;
  check_reject "nonce 9 bytes"
    (legacy_of (replace 0 (b ("89" ^ String.make 18 '1')) legacy_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "gas_price 17 bytes"
    (legacy_of (replace 1 (b ("91" ^ String.make 34 '1')) legacy_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "value 33 bytes"
    (legacy_of (replace 4 (b ("a1" ^ String.make 66 '1')) legacy_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "r 33 bytes"
    (legacy_of (replace 7 (b ("a1" ^ String.make 66 '1')) legacy_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "gas_limit = u64::MAX is unrepresentable here (documented narrowing)"
    (legacy_of (replace 2 (b "88ffffffffffffffff") legacy_fields))
    Tx_envelope.Unrepresentable_scalar

(* The width bounds on the TYPED readers are a separate code path from the legacy
   one above, and they are the port's only guard against accepting an integer
   alloy cannot hold: a chain id is a [u64] ([ChainId]) and the two EIP-1559 fee
   caps are [u128]. Nothing else in the suite reaches [read_eip1559]'s field
   readers with a malformed scalar, so without these the type-2 bounds could be
   deleted and every other test would still pass. *)
let test_reject_typed_scalars () =
  let wide n = b (Printf.sprintf "%02x%s" (0x80 + n) (String.make (2 * n) '1')) in
  (* chain_id is field 0 of both typed layouts; nine bytes exceeds a u64. *)
  check_reject "type 1: chain_id 9 bytes" (t1_of (replace 0 (wide 9) t1_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "type 2: chain_id 9 bytes" (t2_of (replace 0 (wide 9) t2_fields))
    Tx_envelope.Scalar_too_wide;
  (* The fee caps are fields 2 and 3; seventeen bytes exceeds a u128. *)
  check_reject "type 2: max_priority_fee_per_gas 17 bytes"
    (t2_of (replace 2 (wide 17) t2_fields))
    Tx_envelope.Scalar_too_wide;
  check_reject "type 2: max_fee_per_gas 17 bytes" (t2_of (replace 3 (wide 17) t2_fields))
    Tx_envelope.Scalar_too_wide;
  (* And the typed leading-zero rule, likewise unexercised on this path. *)
  check_reject "type 2: chain_id 0x00" (t2_of (replace 0 (b "00") t2_fields))
    Tx_envelope.Leading_zero_scalar;
  (* A sanity anchor: the unmodified type-2 skeleton these are derived from must
     itself decode, or every rejection above would pass for the wrong reason. *)
  check_accept "type 2: the unmodified skeleton decodes" (t2_of t2_fields)

let test_reject_shapes () =
  check_reject "to as 19 bytes"
    (legacy_of (replace 3 (b ("93" ^ String.make 38 '1')) legacy_fields))
    (Tx_envelope.Fixed_width { expected = 20; got = 19 });
  check_reject "to as a list" (legacy_of (replace 3 (b "c0") legacy_fields))
    Tx_envelope.Unexpected_list;
  check_reject "legacy list with 8 items"
    (legacy_of (drop_last legacy_fields))
    (Tx_envelope.Field_count { expected = 9; got = 8 });
  check_reject "legacy list with 10 items"
    (legacy_of (legacy_fields @ [ b "80" ]))
    (Tx_envelope.Field_count { expected = 9; got = 10 });
  check_reject "typed list with 10 items"
    (t1_of (drop_last t1_fields))
    (Tx_envelope.Field_count { expected = 11; got = 10 });
  check_reject "storage key as 31 bytes"
    (t1_of (replace 7 (al_of [ al_item ("94" ^ to_a) [ "9f" ^ String.make 62 '2' ] ]) t1_fields))
    (Tx_envelope.Fixed_width { expected = 32; got = 31 });
  check_reject "access list as a byte string"
    (t1_of (replace 7 (b "80") t1_fields))
    Tx_envelope.Unexpected_string;
  check_reject "access-list item with 3 fields"
    (t1_of
       (replace 7
          (al_of [ Rlp.encode_list [ b ("94" ^ to_a); Rlp.encode_list [ b key32 ]; b "80" ] ])
          t1_fields))
    (Tx_envelope.Field_count { expected = 2; got = 3 })

let test_reject_parity () =
  List.iter
    (fun (label, chunk) ->
      check_reject
        ("legacy v = " ^ label)
        (legacy_of (replace 6 (b chunk) legacy_fields))
        Tx_envelope.Invalid_parity_value)
    [
      ("0", "80"); ("1", "01"); ("26", "1a"); ("29", "1d"); ("34", "22");
      ("35 + 2*2^64 (chain id above u64::MAX)", "89020000000000000023");
    ];
  check_reject "typed y_parity 0x00"
    (t1_of (replace 8 (b "00") t1_fields))
    Tx_envelope.Leading_zero_scalar;
  check_reject "typed y_parity 0x02" (t1_of (replace 8 (b "02") t1_fields))
    Tx_envelope.Invalid_bool;
  check_reject "typed y_parity 0x81 0x01 (non-canonical single byte)"
    (t1_of (replace 8 (b "8101") t1_fields))
    (Tx_envelope.Rlp Rlp.Non_canonical_single_byte)

let test_reject_framing () =
  check_reject "empty input" "" Tx_envelope.Empty_input;
  check_reject "one trailing byte after a valid envelope"
    (legacy_of legacy_fields ^ "\x00")
    (Tx_envelope.Rlp Rlp.Trailing_bytes);
  check_reject "type byte 0x03 (EIP-4844)" ("\x03" ^ Rlp.encode_list t1_fields)
    (Tx_envelope.Unknown_type_byte 3);
  check_reject "type byte 0x05" ("\x05" ^ Rlp.encode_list t1_fields)
    (Tx_envelope.Unknown_type_byte 5);
  check_reject "type byte 0x7f" ("\x7f" ^ Rlp.encode_list t1_fields)
    (Tx_envelope.Unknown_type_byte 0x7f)

(* D-1: the two framings alloy accepts and this port deliberately refuses. Each
   re-hashes, in alloy, to the SAME transaction hash as its canonical twin — so
   accepting them would mean two byte strings sharing one hash. *)
let test_reject_non_canonical_framing () =
  check_reject "0x00-tagged legacy (alloy accepts; this port narrows)"
    ("\x00" ^ legacy_of legacy_fields)
    Tx_envelope.Zero_type_byte;
  check_reject "typed envelope behind an outer RLP string header (alloy accepts)"
    (Rlp.encode_bytes (t1_of t1_fields))
    Tx_envelope.Outer_string;
  check_reject "legacy envelope behind an outer RLP string header"
    (Rlp.encode_bytes (legacy_of legacy_fields))
    Tx_envelope.Outer_string;
  (* And the canonical twins are still accepted, so the rejection is about
     framing and nothing else. *)
  check_accept "the canonical legacy twin still decodes" (legacy_of legacy_fields);
  check_accept "the canonical typed twin still decodes" (t1_of t1_fields)

