(* 7. Transactions roots over real signed envelopes                    *)
(* ------------------------------------------------------------------ *)

let test_transactions_roots () =
  let envelopes = List.map envelope_of Tx_vectors.cases in
  List.iteri
    (fun i expected ->
      let prefix = List.filteri (fun j _ -> j <= i) envelopes in
      Alcotest.(check string)
        (Printf.sprintf "transactions_root_of over the first %d fixtures" (i + 1))
        expected
        (to_hex (Block_roots.transactions_root_of prefix));
      Alcotest.(check string)
        (Printf.sprintf "transactions_root_of = transactions_root . map encode_2718 (%d)" (i + 1))
        (to_hex (Block_roots.transactions_root (List.map Tx_envelope.encode_2718 prefix)))
        (to_hex (Block_roots.transactions_root_of prefix)))
    Tx_vectors.prefix_roots

let () =
  Alcotest.run "tx_envelope"
    [
      ( "encode",
        [
          Alcotest.test_case "golden signing payload, hash, 2718 bytes and tx hash" `Quick
            test_golden_encode;
          Alcotest.test_case "structural constants (to, calldata, access list)" `Quick
            test_structural_constants;
          Alcotest.test_case "the EIP-155 signing tail" `Quick test_eip155_signing_tail;
        ] );
      ( "decode",
        [
          Alcotest.test_case "base chunk vectors decode" `Quick test_base_vectors_decode;
          Alcotest.test_case "golden decode recovers every field" `Quick test_golden_decode;
          Alcotest.test_case "encode_2718 . decode_2718 = id" `Quick test_round_trip;
          Alcotest.test_case "round trip with short r/s (scalars, not fixed width)" `Quick
            test_round_trip_short_scalars;
          Alcotest.test_case "scalar canonicity and width" `Quick test_reject_scalars;
          Alcotest.test_case "typed scalar width (chain id, fee caps)" `Quick
            test_reject_typed_scalars;
          Alcotest.test_case "field shapes and counts" `Quick test_reject_shapes;
          Alcotest.test_case "parity values, legacy and typed" `Quick test_reject_parity;
          Alcotest.test_case "framing: empty, trailing, unknown type" `Quick test_reject_framing;
          Alcotest.test_case "non-canonical framings alloy accepts (D-1 narrowing)" `Quick
            test_reject_non_canonical_framing;
          Alcotest.test_case "must accept: no crypto validation at the RLP layer" `Quick
            test_must_accept;
          Alcotest.test_case "chain_id = Some 0 is distinct from None" `Quick
            test_chain_id_zero_distinct_from_none;
        ] );
      ( "roots",
        [
          Alcotest.test_case "transactions roots over every fixture prefix" `Quick
            test_transactions_roots;
        ] );
    ]
