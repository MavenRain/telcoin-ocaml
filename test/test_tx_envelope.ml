(* Tests for the signed transaction envelope (Tn_evm.Tx_envelope) and its strict
   decoder.

   Independent oracle: Tx_vectors, generated by an out-of-tree cargo project
   pinned to telcoin-network's own lock (alloy-consensus 1.8.3 / alloy-eips 1.8.3
   / alloy-primitives 1.5.7 / alloy-rlp 0.3.13). Fixture 1 reproduces the EIP-155
   specification's own published example byte for byte, so the fixture set is
   externally validated rather than self-referential; see tx_vectors.ml.

   The rejection and acceptance tables below are built from raw RLP chunks rather
   than from the fixtures, so that a non-canonical chunk (a leading-zero scalar,
   a 0x81 0x01 bool) can be injected: Rlp.encode_list concatenates
   already-encoded chunks and computes only the header. *)

module Tx_envelope = Tn_evm.Tx_envelope
module Tx_payload = Tn_evm.Tx_payload
module Tx_signature = Tn_evm.Tx_signature
module Transaction = Tn_evm.Transaction
module Block_roots = Tn_evm.Block_roots
module Rlp = Tn_rlp.Rlp
module U256 = Tn_state.U256
module Nonce = Tn_state.Nonce
module Address = Tn_types.Units.Address

let to_hex = Tx_vectors.to_hex
let b = Tx_vectors.hex

let envelope_of (c : Tx_vectors.case) =
  Tx_envelope.make ~payload:c.payload
    ~signature:
      (Tx_signature.make ~parity:c.parity ~r:(Tx_vectors.w_of_hex c.r)
         ~s:(Tx_vectors.w_of_hex c.s))

(* ------------------------------------------------------------------ *)
(* 1. Golden encode                                                    *)
(* ------------------------------------------------------------------ *)

let test_golden_encode () =
  List.iter
    (fun (c : Tx_vectors.case) ->
      let e = envelope_of c in
      Alcotest.(check string)
        (c.name ^ ": signing_payload") c.signing_payload
        (to_hex (Tx_envelope.signing_payload c.payload));
      Alcotest.(check string)
        (c.name ^ ": signature_hash") c.signing_hash
        (to_hex (Tx_envelope.signature_hash c.payload));
      Alcotest.(check string)
        (c.name ^ ": encode_2718") c.encoded_2718
        (to_hex (Tx_envelope.encode_2718 e));
      Alcotest.(check string) (c.name ^ ": hash") c.tx_hash (to_hex (Tx_envelope.hash e));
      Alcotest.(check string)
        (c.name ^ ": hash_of_2718 agrees with hash")
        c.tx_hash
        (to_hex (Tx_envelope.hash_of_2718 (b c.encoded_2718))))
    Tx_vectors.cases

(* ------------------------------------------------------------------ *)
(* 2. Golden decode — field by field, no wildcard arms                 *)
(* ------------------------------------------------------------------ *)

let kind_equal a c =
  match (a, c) with
  | Transaction.Call x, Transaction.Call y -> Address.equal x y
  | Transaction.Create, Transaction.Create -> true
  | Transaction.Call _, Transaction.Create | Transaction.Create, Transaction.Call _ -> false

let access_list_equal =
  List.equal (fun (a1, k1) (a2, k2) -> Address.equal a1 a2 && List.equal U256.equal k1 k2)

let variant_equal a c =
  match (a, c) with
  | Tx_payload.Legacy x, Tx_payload.Legacy y ->
      Option.equal U256.equal x.chain_id y.chain_id && U256.equal x.gas_price y.gas_price
  | Tx_payload.Eip2930 x, Tx_payload.Eip2930 y ->
      U256.equal x.chain_id y.chain_id && U256.equal x.gas_price y.gas_price
  | Tx_payload.Eip1559 x, Tx_payload.Eip1559 y ->
      U256.equal x.chain_id y.chain_id
      && U256.equal x.max_priority_fee_per_gas y.max_priority_fee_per_gas
      && U256.equal x.max_fee_per_gas y.max_fee_per_gas
  | Tx_payload.Legacy _, (Tx_payload.Eip2930 _ | Tx_payload.Eip1559 _) -> false
  | Tx_payload.Eip2930 _, (Tx_payload.Legacy _ | Tx_payload.Eip1559 _) -> false
  | Tx_payload.Eip1559 _, (Tx_payload.Legacy _ | Tx_payload.Eip2930 _) -> false

let payload_equal a c =
  variant_equal (Tx_payload.variant a) (Tx_payload.variant c)
  && Nonce.equal (Tx_payload.nonce a) (Tx_payload.nonce c)
  && Int.equal (Tx_payload.gas_limit a) (Tx_payload.gas_limit c)
  && kind_equal (Tx_payload.kind a) (Tx_payload.kind c)
  && U256.equal (Tx_payload.value a) (Tx_payload.value c)
  && String.equal (Tx_payload.data a) (Tx_payload.data c)
  && access_list_equal (Tx_payload.access_list a) (Tx_payload.access_list c)
  && Int.equal (Tx_payload.type_byte a) (Tx_payload.type_byte c)

let test_golden_decode () =
  List.iter
    (fun (c : Tx_vectors.case) ->
      let decoded = Tx_envelope.decode_2718 (b c.encoded_2718) in
      let ok =
        Result.fold ~error:(fun _ -> false)
          ~ok:(fun e ->
            payload_equal (Tx_envelope.payload e) c.payload
            && Bool.equal (Tx_signature.parity (Tx_envelope.signature e)) c.parity
            && U256.equal (Tx_signature.r (Tx_envelope.signature e)) (Tx_vectors.w_of_hex c.r)
            && U256.equal (Tx_signature.s (Tx_envelope.signature e)) (Tx_vectors.w_of_hex c.s))
          decoded
      in
      Alcotest.(check bool) (c.name ^ ": decode recovers every field") true ok)
    Tx_vectors.cases

(* ------------------------------------------------------------------ *)
(* 3. Round trip — the theorem the canonical-only accept set buys      *)
(* ------------------------------------------------------------------ *)

let test_round_trip () =
  let round (c : Tx_vectors.case) =
    Result.fold ~error:(fun _ -> "decode failed")
      ~ok:(fun e -> to_hex (Tx_envelope.encode_2718 e))
      (Tx_envelope.decode_2718 (b c.encoded_2718))
  in
  List.iter
    (fun (c : Tx_vectors.case) ->
      Alcotest.(check string) (c.name ^ ": encode_2718 . decode_2718 = id") c.encoded_2718 (round c))
    Tx_vectors.cases

